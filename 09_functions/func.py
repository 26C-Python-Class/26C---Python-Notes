# Finding extremes in a sequence
message = 'Hello world'
print(max(message))  # Output: 'w' (highest ASCII value)
print(min(message))  # Output: ' ' (space has a lower value than letters)

# Finding the "Absolute" value (distance from zero)
print(abs(-15.5))    # Output: 15.5

# Counting items
print(len(message))  # Output: 11